export const FONT_HEIGHT = 9;
export const BASELINE = 7;

export const GLYPHS = Object.fromEntries(
  Object.entries(G).map(([ch, s]) => {
    const rows = s.split('|');
    while (rows.length < FONT_HEIGHT) rows.push('.'.repeat(rows[0].length));
    return [ch, rows];
  }),
);

/** Width in font pixels of `text` with one pixel between glyphs. */
export function measure(text) {
  let w = 0;
  for (const ch of text) {
    const g = GLYPHS[ch];
    if (!g) throw new Error(`font has no glyph for ${JSON.stringify(ch)}`);
    w += g[0].length + 1;
  }
  return Math.max(0, w - 1);
}
