// Builds every Lightpath logo file from the code in brand/logo/src, then checks them.
//   pnpm brand:logo
// SVG files are written from the shape model. PNG and ICO files are drawn from the same shapes by
// src/raster.mjs (our own anti-aliased rasterizer). Nothing here is drawn by hand or by an image
// model, and the build needs no network, no browser and no packages beyond Node itself.
import { mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { runChecks } from './src/check.mjs';
import { CONCEPTS } from './src/concepts.mjs';
import { faviconPixels, faviconSVG, iconPixels, iconSVG } from './src/icons.mjs';
import { horizontal, markOnly, stacked, wordOnly } from './src/lockup.mjs';
import { NOTES, RECOMMENDED } from './src/notes.mjs';
import { onePage } from './src/onepage.mjs';
import { encodeICO, encodePNG } from './src/png.mjs';
import { canvas, toRGBA } from './src/raster.mjs';
import { geometryAt, paintMark } from './src/render.mjs';
import { risoRaster, risoSVG } from './src/riso.mjs';
import { conceptSheet, overviewSheet } from './src/sheet.mjs';
import { toSVG } from './src/svg.mjs';
import { COLOURWAYS, TOKENS } from './src/tokens.mjs';
import { loadFont } from './src/ttf.mjs';

const root = dirname(fileURLToPath(import.meta.url));
const font = loadFont(join(root, 'fonts', 'IBMPlexSans-SemiBold.ttf'));
const fonts = { bold: font };

// Generated folders are rebuilt from scratch so no stale file survives a rename.
for (const dir of ['svg', 'png', 'riso', 'review']) rmSync(join(root, dir), { recursive: true, force: true });

const out = (rel, data) => {
  const p = join(root, rel);
  mkdirSync(dirname(p), { recursive: true });
  writeFileSync(p, data);
};
const png = (c) => encodePNG(c.w, c.h, toRGBA(c));

const concept = CONCEPTS.find((k) => k.id === RECOMMENDED);
const geo = concept.draw();

// 1. Vector logo files: four pieces x four colourways (plus reversed colour for dark backgrounds).
const art = {
  mark: markOnly(geo),
  wordmark: wordOnly(font),
  horizontal: horizontal(font, geo),
  stacked: stacked(font, geo),
};
const names = {
  mark: 'mark',
  wordmark: 'wordmark',
  horizontal: 'lockup-horizontal',
  stacked: 'lockup-stacked',
};
for (const [key, a] of Object.entries(art)) {
  for (const way of ['colour', 'indigo', 'black', 'white', 'reversed']) {
    if (key === 'wordmark' && way === 'reversed') continue; // the wordmark has no pink
    out(`svg/lightpath-${names[key]}-${way}.svg`, toSVG(a, COLOURWAYS[way]));
  }
}

// 2. Favicons, app icon, avatar.
const fav = Object.fromEntries([16, 32, 48].map((s) => [s, faviconPixels(concept, s)]));
for (const s of [16, 32, 48]) out(`png/favicon-${s}.png`, png(fav[s]));
out('png/favicon.ico', encodeICO([16, 32, 48].map((s) => ({ size: s, png: png(fav[s]) }))));
out('svg/favicon.svg', faviconSVG(geometryAt(concept, 16)));
out('svg/app-icon.svg', iconSVG(geo));
const icons = { fav16: fav[16], app256: iconPixels(concept, 256), avatar: iconPixels(concept, 400) };
out('png/apple-touch-icon.png', png(iconPixels(concept, 180)));
// 256 px: the VS Code extension icon (extensions/vscode/media/icon.png is a copy; the check compares).
out('png/app-icon-256.png', png(iconPixels(concept, 256)));
out('png/app-icon-512.png', png(iconPixels(concept, 512)));
out('png/app-icon-1024.png', png(iconPixels(concept, 1024)));
out('png/avatar-400.png', png(icons.avatar));
// Mark PNGs on a transparent background, for places that cannot take SVG.
for (const s of [64, 256, 1024]) {
  const c = canvas(s, s);
  paintMark(c, concept, s, COLOURWAYS.colour);
  out(`png/lightpath-mark-colour-${s}.png`, png(c));
}

// 3. Riso version (website art only).
out('riso/lightpath-mark-riso.svg', risoSVG(art.mark, 1, { pad: 1 }));
out(
  'riso/lightpath-lockup-horizontal-riso.svg',
  risoSVG(art.horizontal, art.horizontal.unit, { pad: art.horizontal.unit }),
);
const riso = {
  mark: risoRaster(art.mark, 1, 300, 1),
  lockup: risoRaster(art.horizontal, art.horizontal.unit, 900, art.horizontal.unit),
};
out('riso/lightpath-mark-riso-preview.png', png(riso.mark));
out('riso/lightpath-lockup-horizontal-riso-preview.png', png(riso.lockup));

// 4. Tokens.
out('tokens.json', `${JSON.stringify(TOKENS, null, 2)}\n`);
out(
  'tokens.css',
  `/* Lightpath logo colours. Generated by brand/logo/build.mjs. */\n:root {\n${Object.entries(TOKENS)
    .map(([k, v]) => `  --${k}: ${v};`)
    .join('\n')}\n}\n`,
);

// 5. Review sheets.
for (const k of CONCEPTS) out(`review/concept-${k.n}-${k.id}.png`, png(conceptSheet(k, fonts, NOTES[k.id])));
out('review/concepts-overview.png', png(overviewSheet(CONCEPTS, fonts)));
const why = NOTES[concept.id].why;
out(
  'review/logo-sheet.png',
  png(onePage({ concept, concepts: CONCEPTS, fonts, art, icons, riso, why, date: '2026-11-04' })),
);

// 6. Checks.
const report = runChecks(root, { fav16: fav[16] });
out('review/check.json', `${JSON.stringify(report, null, 2)}\n`);
console.log(JSON.stringify({ favicon16: report.favicon16, contrast: report.contrast }, null, 2));
if (!report.ok) {
  console.error(`logo check failed:\n${report.fails.join('\n')}`);
  process.exit(1);
}
console.log(`logo check passed, ${Object.keys(report.files).length} files`);
